/** "N" — create the next scene after the (last) selected scene, inheriting its references and settings. */
export function nextScene(position?: XY) {
  const sel = selectedSceneIds()
  const project = useProject.getState().project
  const from = sel.length ? project.scenes.filter((s) => sel.includes(s.id)).sort((a, b) => b.order - a.order)[0] : undefined
  if (!from) return newScene(position)
  const id = useProject.getState().createNextScene(from.id, position)
  useUI.getState().select([id])
  revealNodes([id])
  toast(`Đã tạo cảnh tiếp theo sau ${sceneCode(from.order)} (giữ ảnh tham chiếu và cấu hình).`, { tone: 'success', action: undoToastAction() })
  return id
}

/**
 * Can a new scene take this take's own reference images and settings (createSceneFromVideo)? Not when the take ran on
 * a model this build does not know (a newer build's), its settings are not this build's own values (normalizing would
 * change one), or it was imported ("Nhập job") with settings / references canvasapp did not tell for sure.
 */
function takeSettingsUsable(take: Take): boolean {
  if (take.foreignModel || take.foreignProvider || !isModelId(take.settings?.model)) return false
  if (take.imported && (take.imported.unknown.length > 0 || take.imported.inferred.length > 0)) return false
  return sameSettings(normalizeSettings(take.settings), take.settings)
}

/**
 * "Tạo cảnh tiếp theo từ video này": a new scene next to a finished take, with the reference images and settings that
 * video was made with (its snapshot; characters deleted since are left out), the source scene's frames and preset
 * (the preset only while the take's settings still match it) and an empty prompt — one undo step. When the take's
 * own settings cannot be used here (takeSettingsUsable), the source scene's current images and settings are taken
 * instead (the toast says so). Placed at `position`; else right of the take when the user dragged it out of its
 * scene's row (that is where they look at it); else below the source scene — also for a take only nudged on its slot
 * or resized in place: it is still in the row, and the card right of it would sit where the scene's next take goes.
 */
export function createSceneFromVideo(takeId: string, position?: XY) {
  const take = useRuns.getState().takes.find((t) => t.id === takeId)
  if (!take) return null
  if (take.status !== 'completed') {
    toast('Video chưa tạo xong.', { tone: 'warning' })
    return null
  }
  const project = useProject.getState().project
  const source = project.scenes.find((s) => s.id === take.sceneId)
  if (!source) {
    toast('Cảnh gốc của video này đã bị xoá.', { tone: 'warning' })
    return null
  }
  const leftRow = !!take.position && currentTakeRows().offRow.has(take.id)
  const at =
    position ??
    (leftRow && take.position
      ? freeSpotFrom(project, { x: take.position.x + (take.size?.w ?? LAYOUT.takeW) + LAYOUT.takeOffsetX, y: take.position.y })
      : undefined)
  const usable = takeSettingsUsable(take)
  const alive = new Set(project.assets.map((a) => a.id))
  const refs = take.refsSnapshot.filter((id) => alive.has(id))
  const settings = normalizeSettings(take.settings)
  const preset = source.presetId ? project.presets.find((p) => p.id === source.presetId) : undefined
  const id = useProject
    .getState()
    .createNextScene(source.id, at, usable ? { refs, settings, presetId: preset && sameSettings(presetSettings(preset), settings) && !preset.foreignModel ? preset.id : null } : {})
  useUI.getState().select([id])
  revealNodes([id])
  const code = sceneCode(useProject.getState().project.scenes.find((s) => s.id === id)?.order ?? source.order + 1)
  const dropped = take.refsSnapshot.length - refs.length
  toast(
    usable
      ? `Đã tạo ${code} tiếp theo ${takeLabel(takeId)} — cùng ảnh tham chiếu và cấu hình của video đó, prompt để trống${dropped ? ` (bỏ ${dropped} nhân vật đã xoá)` : ''}.`
      : `Đã tạo ${code} tiếp theo ${takeLabel(takeId)} — dùng ảnh và cấu hình hiện tại của ${sceneCode(source.order)} (cấu hình của video không dùng được ở bản này), prompt để trống.`,
    { tone: 'success', action: undoToastAction() },
  )
  return id
}

