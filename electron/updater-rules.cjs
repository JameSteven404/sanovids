/**
 * Real HTML element names (what GitHub renders release notes with, plus the dangerous ones). Only these make notes
 * "HTML" and only these are stripped: "<phiên bản>", "<version>" or "a < 5 và > 3" are text and stay text.
 */
const HTML_TAGS =
  'a|abbr|article|aside|b|blockquote|body|br|button|caption|center|code|col|colgroup|dd|del|details|dfn|div|dl|dt|em|embed|' +
  'figcaption|figure|font|footer|form|g-emoji|h[1-6]|head|header|hr|html|i|iframe|img|input|ins|kbd|li|link|main|mark|meta|' +
  'nav|object|ol|p|picture|pre|q|s|samp|script|section|small|source|span|strike|strong|style|sub|summary|sup|svg|table|' +
  'tbody|td|template|tfoot|th|thead|time|title|tr|tt|u|ul|var|video'
const HTML_TAG_RE = new RegExp(`</?(?:${HTML_TAGS})(?=[\\s/>])[^>]*>`, 'i')
const HTML_TAG_RE_G = new RegExp(HTML_TAG_RE.source, 'gi')
/** Whitespace between two real tags (meaningless in HTML). */
const BETWEEN_TAGS_RE = new RegExp(`(${HTML_TAG_RE.source})\\s+(?=${HTML_TAG_RE.source})`, 'gi')
const ENTITY_RE = /&(#x[0-9a-f]{1,6}|#\d{1,7}|amp|lt|gt|quot|apos|nbsp);/gi
const NAMED_ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ' }

function decodeEntities(s) {
  // One pass: "&amp;lt;" becomes "&lt;" (text), never "<".
  return s.replace(ENTITY_RE, (whole, body) => {
    const lower = body.toLowerCase()
    if (lower[0] !== '#') return NAMED_ENTITIES[lower]
    const cp = lower[1] === 'x' ? parseInt(lower.slice(2), 16) : parseInt(lower.slice(1), 10)
    if (!Number.isFinite(cp) || cp <= 0 || cp > 0x10ffff || (cp >= 0xd800 && cp <= 0xdfff)) return ''
    return String.fromCodePoint(cp)
  })
}

/** GitHub-rendered HTML → markdown-ish plain text (entities decoded last, so they always stay text). */
function htmlToText(s) {
  return decodeEntities(
    s
      .replace(/<(script|style)\b[\s\S]*?<\/\1\s*>/gi, '')
      // Whitespace between two tags means nothing in HTML (only the tags below break lines there). Newlines inside text
      // are kept: markdown notes with one inline tag ("- <b>x</b>") also land here and must keep their lines.
      .replace(BETWEEN_TAGS_RE, '$1')
      .replace(/[ \t\f\v]+/g, ' ')
      .replace(/<br\s*\/?>/gi, '\n')
      .replace(/<\/(p|div|li|ul|ol|h[1-6])\s*>/gi, '\n')
      .replace(/<li\b[^>]*>/gi, '- ')
      .replace(/<h[1-6]\b[^>]*>/gi, '## ')
      .replace(HTML_TAG_RE_G, '')
      .replace(/^ +| +$/gm, ''),
  )
}

function noteText(s) {
  const t = s.replace(/\r\n?/g, '\n')
  return HTML_TAG_RE.test(t) ? htmlToText(t) : t
}

/**
 * releaseNotes of latest.yml / the GitHub feed → PLAIN TEXT (markdown-ish, never HTML), at most 8000 chars.
 * Accepts a string (markdown or HTML) or electron-updater's [{ version, note }] list.
 */
function notesToText(releaseNotes) {
  let text = ''
  if (typeof releaseNotes === 'string') text = noteText(releaseNotes)
  else if (Array.isArray(releaseNotes)) {
    text = releaseNotes
      .filter((r) => r && typeof r === 'object')
      .map((r) => {
        const version = typeof r.version === 'string' ? r.version.slice(0, VERSION_MAX) : ''
        const note = typeof r.note === 'string' ? noteText(r.note) : ''
        return [version, note].filter(Boolean).join('\n')
      })
      .filter(Boolean)
      .join('\n\n')
  }
  text = text
    .replace(/\r/g, '\n')
    .replace(/[\u0000-\u0008\u000b-\u001f\u007f-\u009f]/g, '')
    .replace(/[ \t]+$/gm, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
  if (text.length > NOTES_MAX) {
    let head = text.slice(0, NOTES_MAX - 1)
    const nl = head.lastIndexOf('\n')
    if (nl > 0) head = head.slice(0, nl)
    else if (/[\ud800-\udbff]$/.test(head)) head = head.slice(0, -1)
    text = head.trimEnd() + '…'
  }
  return text
}

/** UpdateInfo of electron-updater → { version, releaseDate?, notes, size? } | null (invalid version: ignore the event). */
function normalizeInfo(info) {
  if (!info || typeof info !== 'object' || !isVersion(info.version)) return null
  const out = { version: info.version, notes: notesToText(info.releaseNotes) }
  if (typeof info.releaseDate === 'string' && info.releaseDate) out.releaseDate = info.releaseDate.slice(0, RELEASE_DATE_MAX)
  const first = Array.isArray(info.files) ? info.files[0] : null
  const size = first && typeof first === 'object' ? first.size : undefined
  if (typeof size === 'number' && Number.isFinite(size) && size >= 0) out.size = size
  return out
}

