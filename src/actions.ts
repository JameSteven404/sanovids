/** Zip with the reference images/videos named in token order (image_01_Elara.png, video_01_S03-T2.webm) + prompt.txt. */
export async function downloadSceneZip(sceneId: string) {
  const c = compiledFor(sceneId)
  if (!c) return
  const { project, scene, compiled } = c
  const { default: JSZip } = await import('jszip')
  const zip = new JSZip()
  zip.file('prompt.txt', compiled.text)
  for (const img of compiled.images) {
    const blob = await getBlob(img.imageId)
    if (!blob) continue
    const asset = project.assets.find((a) => a.id === img.assetId)
    const ext = blob.type.includes('png') ? 'png' : blob.type.includes('webp') ? 'webp' : blob.type.includes('svg') ? 'svg' : 'jpg'
    zip.file(`image_${String(img.n).padStart(2, '0')}_${asset?.tag ?? 'image'}.${ext}`, blob)
  }
  const takes = useRuns.getState().takes
  for (const v of compiled.videos) {
    const take = takes.find((t) => t.id === v.takeId)
    const blob = take?.videoId ? await getBlob(take.videoId) : null
    if (!blob) continue
    zip.file(`video_${String(v.n).padStart(2, '0')}_${takeLabel(v.takeId).replace('·', '-')}.webm`, blob)
  }
  const out = await zip.generateAsync({ type: 'blob' })
  const url = URL.createObjectURL(out)
  const a = document.createElement('a')
  a.href = url
  a.download = `${sceneCode(scene.order)}${scene.title ? '_' + scene.title.replace(/[<>:"/\\|?*]/g, '-') : ''}.zip`
  a.click()
  setTimeout(() => URL.revokeObjectURL(url), 10000)
}

