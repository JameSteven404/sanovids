/** Explicit take selection; uses the same save flow as the project ZIP. */
export async function downloadTakesZip(takeIds: readonly string[]) {
  const ready = new Map(useRuns.getState().takes.filter((t) => t.status === 'completed').map((t) => [t.id, t]))
  const ids = [...new Set(takeIds)].filter((id) => ready.has(id))
  if (!ids.length) {
    toast('Chưa có video nào tạo xong.', { tone: 'warning' })
    return
  }
  const name = `${useProject.getState().project.name.replace(/[<>:"/\\|?*]/g, '-')} - video chọn.zip`
  const askWhere = useDownloadPrefs.getState().askWhere
  // Ask now, while the click still counts as a user gesture (zipping takes a while): where to save the .zip, or
  // the permission for the chosen download folder.
  const plan = askWhere ? await prepareSaveAs(name, { title: 'Lưu file .zip' }) : null
  if (plan === 'canceled') return
  if (!askWhere) await prepareFolderAccess()
  const { default: JSZip } = await import('jszip')
  const zip = new JSZip()
  const prompts: string[] = []
  // Two takes renamed alike must not overwrite each other inside the zip.
  const used = new Set<string>(['prompts.txt'])
  for (const id of ids) {
    const take = ready.get(id)!
    const base = takeFileBase(id)
    for (const f of await takeFiles(take, base, false)) zip.file(uniqueInSet(f.name, used), f.data)
    prompts.push(`=== ${base} ===\n${take.promptSnapshot}`)
  }
  // "Kèm prompts.txt trong file .zip" (Settings → Nâng cao).
  if (useDownloadPrefs.getState().zipPrompts) zip.file('prompts.txt', prompts.join('\n\n'))
  const blob = await zip.generateAsync({ type: 'blob' })
  const file: FileToSave = { name, data: blob }
  try {
    if (plan) {
      reportSavedAs(await runSaveAs(plan, [file]), `${ids.length} video (.zip)`)
      return
    }
    const res = await saveFiles([file], true)
    reportSaved(res, `${ids.length} video (.zip)`, name)
  } catch (e) {
    toast(`Không lưu được file .zip: ${(e as Error).message}`, { tone: 'error' })
  }
}

