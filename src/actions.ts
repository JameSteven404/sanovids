// ---------------- edge ids ----------------
/**
 * ref   asset → scene   (reference image, @image_N)
 * first / last  asset → scene (H3 transform frames)
 * out   scene → take    (the take was generated by the scene; not deletable)
 * save      take  → folder node (that video is copied into the folder)
 * autosave  scene → folder node (every new finished take of the scene is copied into the folder)
 * (`vref`, take → scene as @video_N, was retired with reference videos in 0.6.0: never drawn, never parsed — and never
 * reused with another meaning.)
 */
export type EdgeKind = 'ref' | 'first' | 'last' | 'out' | FolderLinkKind
export const edgeId = (kind: EdgeKind, from: string, to: string) => `${kind}:${from}->${to}`
export function parseEdgeId(id: string): { kind: EdgeKind; from: string; to: string } | null {
  const m = /^(ref|first|last|out|save|autosave):(.+)->(.+)$/.exec(id)
  return m ? { kind: m[1] as EdgeKind, from: m[2], to: m[3] } : null
}
/** Wires that end at a folder node. */
export const isFolderEdge = (kind: EdgeKind): kind is FolderLinkKind => kind === 'save' || kind === 'autosave'

