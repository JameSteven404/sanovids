/**
 * The one way to delete takes for good (canvas node, take viewer, queue, Delete key): asks when needed, cancels
 * running jobs, removes the takes (folder nodes forget them), deletes their poster/video files (nothing can bring a deleted take back, so its media would only fill the
 * browser's quota), drops them from the selection and says so in a toast.
 * Returns how many takes were deleted, or null when the user cancelled the question.
 */
/**
 * Takes as checkTakeDelete sees them: a running take whose video is already made and paid (remoteVideoReady:
 * downloading, or waiting for its next try) is asked about like a finished one — deleting it drops that paid video.
 */
function deleteFacts(takes: readonly Take[]): { id: string; status: Take['status']; videoReady: boolean; provider: string }[] {
  return takes.map((t) => ({ id: t.id, status: t.status, videoReady: t.status === 'processing' && remoteVideoReady(t.id), provider: providerOf(t) }))
}

export function deleteTakes(takeIds: readonly string[], opts: DeleteTakesOptions = {}): number | null {
  const project = useProject.getState().project
  const all = useRuns.getState().takes
  // A video whose cut wire's saved copy is going to the Recycle Bin right now waits: deleting it meanwhile would leave
  // the only copy in the Recycle Bin (folderActions "never the last copy").
  const busy = takesBeingTrashed(takeIds)
  if (busy.length) {
    toast(trashBusyDeleteText(busy.length === 1 ? takeLabel(busy[0]) : `${busy.length} video`), { tone: 'warning' })
    takeIds = takeIds.filter((id) => !busy.includes(id))
  }
  const check = checkTakeDelete(takeIds, deleteFacts(all), { confirm: opts.confirm ?? true, label: takeIds.length === 1 ? takeLabel(takeIds[0]) : undefined })
  if (!check.ids.length) return 0
  if (check.question && !window.confirm(check.question)) return null
  // Labels before the takes are gone.
  const label = check.ids.length === 1 ? takeLabel(check.ids[0]) : `${check.ids.length} video`
  const ids = new Set(check.ids)
  const dead = all.filter((t) => ids.has(t.id))
  useRuns.getState().removeTakes(check.ids)
  for (const t of dead) {
    if (t.posterId) void deleteMedia(t.posterId).catch(() => undefined)
    if (t.videoId) void deleteMedia(t.videoId).catch(() => undefined)
  }
  const ui = useUI.getState()
  if (ui.selectedIds.some((id) => ids.has(id))) ui.select(ui.selectedIds.filter((id) => !ids.has(id)))
  // toast: false → the caller's own toast reports it.
  if (opts.toast ?? true) toast(`Đã xoá ${label}. ${TAKES_GONE_NOTE}`)
  return dead.length
}

/**
 * Delete takes for good without asking and without a toast.
 * @deprecated use `deleteTakes(ids, { confirm, toast })`.
 */
export function deleteTakesForever(takeIds: string[]): number {
  return deleteTakes(takeIds, { confirm: false, toast: false }) ?? 0
}

