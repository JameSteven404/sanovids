/**
 * "Tên file": rename the video of a take (every later save uses it: download, zip, auto-download, folder nodes).
 * The name is sanitized (no path, no forbidden characters, extension dropped); empty or the default name = back to
 * the default. Returns the name now used (without extension). Takes are not undoable: the toast says how to go back.
 */
export function renameTake(takeId: string, raw: string): string | null {
  const take = useRuns.getState().takes.find((t) => t.id === takeId)
  if (!take) return null
  const clean = cleanTakeFileName(raw)
  const next = clean && clean !== defaultTakeFileBase(takeId) ? clean : null
  if ((take.fileName ?? null) !== next) {
    useRuns.getState().setTakeFileName(takeId, next)
    toast(next ? `${takeLabel(takeId)}: tên file mới “${next}”.` : `${takeLabel(takeId)}: dùng lại tên file mặc định.`, { tone: 'success' })
  }
  return takeFileBase(takeId)
}

/** One-click download of a finished take: the video (+ a .txt with the prompt that was sent). */
export async function downloadTake(takeId: string, opts: { auto?: boolean } = {}) {
  const take = useRuns.getState().takes.find((t) => t.id === takeId)
  if (!take || take.status !== 'completed') {
    if (!opts.auto) toast('Video chưa tạo xong.', { tone: 'warning' })
    return false
  }
  const files = await takeFiles(take, takeFileBase(takeId), useDownloadPrefs.getState().withPrompt)
  if (!files.length) {
    if (!opts.auto) toast('Không tìm thấy file video của take này.', { tone: 'error' })
    return false
  }
  // "Hỏi nơi lưu & tên file": a click asks where (a background auto-download never does).
  if (!opts.auto && useDownloadPrefs.getState().askWhere) {
    try {
      const res = await saveFilesAs(files, { title: `Lưu video ${takeLabel(takeId)}` })
      reportSavedAs(res, `${takeLabel(takeId)}${files.length > 1 ? ' + prompt' : ''}`)
      return res.to !== 'canceled'
    } catch (e) {
      toast(`Không lưu được video: ${(e as Error).message}`, { tone: 'error' })
      return false
    }
  }
  try {
    const res = await saveFiles(files, !opts.auto)
    reportSaved(res, `${takeLabel(takeId)}${files.length > 1 ? ' + prompt' : ''}`, files[0].name)
    return res.to !== 'pending'
  } catch (e) {
    toast(`Không lưu được video: ${(e as Error).message}`, { tone: 'error' })
    return false
  }
}

/** Toast for a finished save: where the files went, and what to do when the chosen folder could not be used. */
function reportSaved(res: SaveResult, what: string, firstName: string) {
  const renamed = res.to === 'folder' && res.names[0] && res.names[0] !== firstName ? ` (tên “${res.names[0]}” vì đã có file trùng tên)` : ''
  const extra = res.alsoSaved ? ` và ${res.alsoSaved} file đang chờ` : ''
  if (res.to === 'folder') toast(`Đã lưu ${what}${extra} vào thư mục “${res.folder}”${renamed}.`, { tone: 'success' })
  else if (res.to === 'pending')
    toast(`${what} đang chờ lưu vào “${res.folder}”: trình duyệt cần bạn cho phép ghi vào thư mục này lần nữa.`, {
      tone: 'warning',
      ms: 20000,
      action: { label: 'Cho phép & lưu', run: () => void savePendingNow() },
    })
  else if (res.reason === 'missing-folder')
    toast(`Không tìm thấy thư mục “${res.folder}” (đã đổi tên hoặc xoá?) nên đã tải ${what} về thư mục Downloads. Chọn lại thư mục trong Cài đặt.`, {
      tone: 'warning',
      ms: 8000,
    })
  else if (res.reason === 'no-permission')
    toast(`Chưa có quyền ghi vào “${res.folder}” nên đã tải ${what} về thư mục Downloads.`, { tone: 'warning', ms: 8000 })
  else toast(`Đã tải ${what} về máy.`, { tone: 'success' })
}

/** Toast for a "save as" (askWhere): where it went, or why the browser downloaded it instead. Nothing on cancel. */
function reportSavedAs(res: SaveAsResult, what: string) {
  if (res.to === 'canceled') return
  if (res.to === 'chosen') {
    const where = res.path ? ` → ${res.path}` : ` → “${res.names[0]}”`
    const extra = res.names.length > 1 ? ` (kèm “${res.names.slice(1).join('”, “')}”${res.path ? ' cùng chỗ' : ' trong Tải xuống'})` : ''
    toast(`Đã lưu ${what}${where}${extra}.`, { tone: 'success', ms: 6000 })
    return
  }
  toast(
    `Trình duyệt này không cho chọn nơi lưu nên đã tải ${what} về thư mục Tải xuống (Downloads). Dùng Chrome / Edge hoặc app SanoVids desktop để chọn nơi lưu và đặt tên.`,
    { tone: 'info', ms: 9000 },
  )
}

/** Toast button (a click, so the browser may ask for the folder permission): save the auto-downloads that wait. */
async function savePendingNow() {
  try {
    const res = await savePendingDownloads()
    if (!res) return
    if (res.to === 'folder') toast(`Đã lưu ${res.names.length} file vào thư mục “${res.folder}”.`, { tone: 'success' })
    else toast(`Chưa được phép ghi vào thư mục nên đã tải ${res.names.length} file về Downloads.`, { tone: 'warning' })
  } catch (e) {
    toast(`Không lưu được: ${(e as Error).message}`, { tone: 'error' })
  }
}

/** The chosen take of every scene (starred, else the latest completed), in scene order. */
export function chosenTakeIds(): string[] {
  const takes = useRuns.getState().takes
  const scenes = [...useProject.getState().project.scenes].sort((a, b) => a.order - b.order)
  const out: string[] = []
  for (const s of scenes) {
    const own = takes.filter((t) => t.sceneId === s.id && t.status === 'completed')
    const pick = own.find((t) => t.starred) ?? own.sort((a, b) => b.number - a.number)[0]
    if (pick) out.push(pick.id)
  }
  return out
}

/** Zip of the chosen take of every scene (S01_T2 - title.webm …) + prompts.txt (pref zipPrompts). */
export async function downloadChosenTakesZip() {
  const ids = chosenTakeIds()
  if (!ids.length) {
    toast('Chưa có video nào tạo xong.', { tone: 'warning' })
    return
  }
  const name = `${useProject.getState().project.name.replace(/[<>:"/\\|?*]/g, '-')} - video chọn.zip`
  const askWhere = useDownloadPrefs.getState().askWhere
  // Ask now, while the click still counts as a user gesture (zipping takes a while): where to save the .zip, or
  // the permission for the chosen download folder.
  const plan = askWhere ? await prepareSaveAs(name, { title: 'Lưu file .zip' }) : null
  if (plan === 'canceled') return
  if (!askWhere) await prepareFolderAccess()
  const { default: JSZip } = await import('jszip')
  const zip = new JSZip()
  const prompts: string[] = []
  // Two takes renamed alike must not overwrite each other inside the zip.
  const used = new Set<string>(['prompts.txt'])
  for (const id of ids) {
    const take = useRuns.getState().takes.find((t) => t.id === id)!
    const base = takeFileBase(id)
    for (const f of await takeFiles(take, base, false)) zip.file(uniqueInSet(f.name, used), f.data)
    prompts.push(`=== ${base} ===\n${take.promptSnapshot}`)
  }
  // "Kèm prompts.txt trong file .zip" (Settings → Nâng cao).
  if (useDownloadPrefs.getState().zipPrompts) zip.file('prompts.txt', prompts.join('\n\n'))
  const blob = await zip.generateAsync({ type: 'blob' })
  const file: FileToSave = { name, data: blob }
  try {
    if (plan) {
      reportSavedAs(await runSaveAs(plan, [file]), `${ids.length} video (.zip)`)
      return
    }
    const res = await saveFiles([file], true)
    reportSaved(res, `${ids.length} video (.zip)`, name)
  } catch (e) {
    toast(`Không lưu được file .zip: ${(e as Error).message}`, { tone: 'error' })
  }
}

