/**
 * Delete what is selected: cut selected wires, delete scenes, hide asset nodes from the canvas (one undo step),
 * and delete selected takes for good (after confirmation when a finished video would be lost; takes are not
 * undoable). Takes selected together with their own scene are spared (keyboardDeletePlan): deleting
 * the scene hides them and Undo brings them back. Cut take → folder wires take the files they copied to the Recycle
 * Bin when that setting is on (folderActions.afterSaveUnlinked; asked first from TRASH_CONFIRM_MIN videos on).
 */
export function deleteSelection() {
  const { selectedIds, selectedEdgeIds } = useUI.getState()
  const project = useProject.getState().project
  const takes = useRuns.getState().takes
  const sceneById = new Map(project.scenes.map((s) => [s.id, s]))
  const assetSet = new Set(project.assets.map((a) => a.id))

  const folderSet = new Set((project.folders ?? []).map((f) => f.id))
  const sceneIds = selectedIds.filter((id) => sceneById.has(id))
  const hideAssetIds = selectedIds.filter((id) => assetSet.has(id))
  const folderIds = selectedIds.filter((id) => folderSet.has(id))
  const plan = keyboardDeletePlan(selectedIds, new Set(sceneById.keys()), new Map(takes.map((t) => [t.id, t.sceneId])))
  const takeIds = plan.takes
  const deadScenes = new Set(sceneIds)

  const refs: { sceneId: string; assetId: string }[] = []
  const frames: { sceneId: string; which: 'first' | 'last' }[] = []
  const folderLinks: { folderId: string; kind: FolderLinkKind; from: string }[] = []
  for (const id of selectedEdgeIds) {
    const e = parseEdgeId(id)
    if (!e) continue
    if (isFolderEdge(e.kind)) {
      // Wires into a folder node that is deleted anyway go with it.
      if (folderSet.has(e.to) && !folderIds.includes(e.to)) folderLinks.push({ folderId: e.to, kind: e.kind, from: e.from })
      continue
    }
    const scene = sceneById.get(e.to)
    // Skip wires that no longer exist or whose scene is being deleted anyway.
    if (!scene || deadScenes.has(scene.id)) continue
    if (e.kind === 'ref' && scene.refs.includes(e.from)) refs.push({ sceneId: e.to, assetId: e.from })
    else if (e.kind === 'first' && scene.firstFrame === e.from) frames.push({ sceneId: e.to, which: 'first' })
    else if (e.kind === 'last' && scene.lastFrame === e.from) frames.push({ sceneId: e.to, which: 'last' })
  }

  const links = refs.length + frames.length + folderLinks.length
  // Take → folder wires that exist (their cut may move the files they copied to the Recycle Bin).
  const folderById = new Map((project.folders ?? []).map((f) => [f.id, f]))
  const savePairs = folderLinks.filter((l) => l.kind === 'save' && folderById.get(l.folderId)?.takes?.includes(l.from)).map((l) => ({ folderId: l.folderId, takeId: l.from }))
  // Ask BEFORE changing anything: Cancel must leave the whole selection untouched.
  if (takeIds.length) {
    const check = checkTakeDelete(takeIds, deleteFacts(takes), { label: takeIds.length === 1 ? takeLabel(takeIds[0]) : undefined })
    if (check.question && !window.confirm(check.question)) return
  }
  // Decided now, once (the question below is about it): what happens to the cut wires' files.
  const trash = savePairs.length > 0 && trashAllowed()
  if (trash && savePairs.length >= TRASH_CONFIRM_MIN) {
    // Videos whose files this Delete would move: finished, kept, with copies their wire wrote itself.
    const movers = trashMoverPairs(savePairs, new Set(takeIds))
    const videos = new Set(movers.map((p) => p.takeId)).size
    if (videos >= TRASH_CONFIRM_MIN && !window.confirm(trashConfirmText(videos, movers.map((p) => folderById.get(p.folderId)?.name ?? 'Thư mục')))) return
  }
  // Takes first: their labels ("S01·T1") need their scene, which deleteItems may remove.
  const projectBefore = useProject.getState().project
  // The canvas animates the wires being cut (before they vanish from the store).
  if (links) {
    announceWireCuts([
      ...refs.map((r) => edgeId('ref', r.assetId, r.sceneId)),
      ...frames.map((f) => {
        const s = sceneById.get(f.sceneId)
        return edgeId(f.which, (f.which === 'first' ? s?.firstFrame : s?.lastFrame) ?? '', f.sceneId)
      }),
      ...folderLinks.map((l) => edgeId(l.kind, l.from, l.folderId)),
    ])
  }
  const takesDeleted = takeIds.length ? (deleteTakes(takeIds, { confirm: false, toast: false }) ?? 0) : 0
  if (sceneIds.length || hideAssetIds.length || folderIds.length || links) {
    useProject.getState().deleteItems({ sceneIds, hideAssetIds, refs, frames, folderIds, folderLinks })
  }
  // After the store change, in each folder's lock: the cut wires' files (setting on), one summary toast.
  if (savePairs.length) void afterSaveUnlinked(savePairs, { source: 'delete', toast: 'summary', undo: undoToastAction(), trash })
  if (!sceneIds.length && !hideAssetIds.length && !folderIds.length && !links && !takesDeleted) return
  useUI.getState().clearSelection()
  const deleted = [
    sceneIds.length && `${sceneIds.length} cảnh`,
    takesDeleted && `${takesDeleted} video`,
    folderIds.length && `${folderIds.length} thư mục khỏi canvas (file đã lưu vẫn còn)`,
    links && `${links} dây nối`,
  ].filter(Boolean)
  const said = [deleted.length && `Đã xoá ${deleted.join(', ')}`, hideAssetIds.length && `${deleted.length ? 'đã ẩn' : 'Đã ẩn'} ${hideAssetIds.length} thẻ khỏi canvas`]
  const undoable = sceneIds.length || hideAssetIds.length || folderIds.length || links
  // Cut image wires leave red placeholders (and, renumbering off, numbers that may now name another picture).
  const note = refs.length ? mediaChangeNote(projectBefore, useProject.getState().project) : null
  const tail = note?.tone === 'warning' ? note.text : ''
  toast(`${said.filter(Boolean).join('; ')}${tail}.${takesDeleted ? ' ' + TAKES_GONE_NOTE : ''}`, {
    ...(undoable ? { action: undoToastAction() } : {}),
    ...(tail ? { tone: 'warning' as const, ms: note?.ms ?? 8000 } : {}),
  })
}

