const PROGRESS_KEYS = ['percent', 'transferred', 'total', 'bytesPerSecond']
const RELEASE_KEYS = ['version', 'releaseDate', 'notes', 'size']

function without(state, keys) {
  const out = { ...state }
  for (const k of keys) delete out[k]
  return out
}

function initialState({ kind, current, autoDownload, notice }) {
  const state = {
    kind,
    current: typeof current === 'string' ? current.slice(0, VERSION_MAX) : '',
    status: kind === 'dev' ? 'unsupported' : 'idle',
    autoDownload: autoDownload !== false,
  }
  if (notice) state.notice = notice
  return state
}

function finiteNonNeg(v) {
  return typeof v === 'number' && Number.isFinite(v) && v >= 0 ? v : undefined
}

function progressFields(p) {
  const o = p && typeof p === 'object' ? p : {}
  const out = {}
  const percent = finiteNonNeg(o.percent)
  if (percent !== undefined) out.percent = Math.min(100, percent)
  for (const k of ['transferred', 'total', 'bytesPerSecond']) {
    const v = finiteNonNeg(o[k])
    if (v !== undefined) out[k] = v
  }
  return out
}

function releaseFields(info) {
  const out = { version: info.version }
  if (typeof info.releaseDate === 'string' && info.releaseDate) out.releaseDate = info.releaseDate.slice(0, RELEASE_DATE_MAX)
  if (typeof info.notes === 'string') out.notes = info.notes.slice(0, NOTES_MAX)
  const size = finiteNonNeg(info.size)
  if (size !== undefined) out.size = size
  return out
}

function validError(error, fallbackCode) {
  if (error && ERROR_CODES.includes(error.code) && typeof error.message === 'string') {
    return { code: error.code, message: error.message.slice(0, 300) }
  }
  return { code: fallbackCode, message: ERROR_TEXT[fallbackCode] || FAILED_TEXT.check }
}

/**
 * The updater state machine (docs: SPEC A.4). Pure: returns the same object when nothing changes.
 * `event.info` is the output of normalizeInfo; `event.error` the output of mapUpdaterError.
 */
function reduceUpdateState(state, event, now) {
  if (!event || typeof event !== 'object') return state
  const busy = state.status === 'downloading' || state.status === 'ready'
  switch (event.type) {
    case 'checking':
      // A known update stays announced while it is checked again: no pill flicker, and a failed re-check (electron-updater
      // always emits checking-for-update first) keeps it instead of turning it into an error.
      if (busy || state.status === 'available') return state
      return { ...without(state, ['error']), status: 'checking' }
    case 'not-available':
      if (busy) return { ...state, lastCheck: now }
      return { ...without(state, [...RELEASE_KEYS, ...PROGRESS_KEYS, 'error']), status: 'none', lastCheck: now }
    case 'available': {
      const info = event.info
      if (!info || !isVersion(info.version)) return state
      if (busy && info.version === state.version) return { ...state, lastCheck: now }
      return { ...without(state, [...RELEASE_KEYS, ...PROGRESS_KEYS, 'error']), ...releaseFields(info), status: 'available', lastCheck: now }
    }
    case 'progress':
      return { ...without(state, [...PROGRESS_KEYS, 'error']), ...progressFields(event.p), status: 'downloading' }
    case 'downloaded': {
      const info = event.info
      let next = without(state, [...PROGRESS_KEYS, 'error'])
      if (info && isVersion(info.version) && info.version !== state.version) next = { ...without(next, RELEASE_KEYS), ...releaseFields(info) }
      return { ...next, status: 'ready', percent: 100 }
    }
    case 'cancelled':
      return { ...without(state, PROGRESS_KEYS), status: 'available' }
    case 'check-error':
      if (busy || state.status === 'available') return { ...state, lastCheck: now }
      return { ...state, status: 'error', error: validError(event.error, 'failed'), lastCheck: now }
    case 'download-error':
      return { ...without(state, PROGRESS_KEYS), status: 'error', error: validError(event.error, 'failed') }
    case 'install-error':
      return { ...state, status: 'ready', error: { code: 'install-failed', message: ERROR_TEXT['install-failed'] } }
    case 'prefs': {
      const autoDownload = event.autoDownload === true
      return state.autoDownload === autoDownload ? state : { ...state, autoDownload }
    }
    default:
      return state
  }
}

/** Is an automatic check due? Every 4 h; 30 min after an offline / rate-limited failure; never during one. */
function checkDue({ status, lastAttemptAt, lastErrorCode, now }) {
  if (status === 'checking' || status === 'downloading') return false
  if (typeof lastAttemptAt !== 'number' || !Number.isFinite(lastAttemptAt)) return true
  const wait = lastErrorCode === 'offline' || lastErrorCode === 'rate-limited' ? CHECK_RETRY_MS : CHECK_EVERY_MS
  return now - lastAttemptAt >= wait
}

